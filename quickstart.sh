#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT_DIR"

if ! command -v docker >/dev/null 2>&1; then
  echo "Error: docker is not installed or not in PATH." >&2
  exit 1
fi

if ! docker compose version >/dev/null 2>&1; then
  echo "Error: docker compose plugin is required." >&2
  exit 1
fi

rand_hex() {
  local bytes="$1"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$bytes"
  else
    od -An -tx1 -N "$bytes" /dev/urandom | tr -d ' \n'
  fi
}

detect_docker_gid() {
  if [ -S /var/run/docker.sock ]; then
    stat -c '%g' /var/run/docker.sock 2>/dev/null || stat -f '%g' /var/run/docker.sock 2>/dev/null || echo "999"
  else
    echo "999"
  fi
}

if [ ! -f .env ]; then
  echo "[pgvault] Generating secure .env configuration..."
  DB_PASS="$(rand_hex 16)"
  KEK_HEX="$(rand_hex 32)"
  API_KEY="$(rand_hex 24)"
  DOCKER_GID="$(detect_docker_gid)"

  cat > .env <<EOF
# Auto-generated by quickstart.sh (keep this file private; ignored by git)
POSTGRES_USER=pgvault
POSTGRES_PASSWORD=${DB_PASS}
POSTGRES_DB=pgvault
PGVAULT_DB_DSN=postgres://pgvault:${DB_PASS}@app-db:5432/pgvault?sslmode=disable

PGVAULT_KEK_HEX=${KEK_HEX}
PGVAULT_API_KEY=${API_KEY}
PGVAULT_API_ADDR=:8080
PGVAULT_API_PORT=8080
PGVAULT_CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000

PGVAULT_WORKER_ID=pgvault-worker-1
PGVAULT_POLL_INTERVAL=5s
PGVAULT_SCHEDULER_INTERVAL=15s
PGVAULT_PRUNE_INTERVAL=1m
PGVAULT_JOB_LEASE_DURATION=15m
PGVAULT_DEFAULT_BUCKET=pgvault-backups

DOCKER_GID=${DOCKER_GID}

NEXT_PUBLIC_API_URL=http://localhost:8080
NEXT_PUBLIC_API_KEY=${API_KEY}
PGVAULT_WEB_PORT=3000
EOF
  chmod 600 .env
  echo "[pgvault] Created .env with random KEK, API key, and DB password."
else
  echo "[pgvault] Using existing .env file."
fi

# shellcheck disable=SC1091
set -a
source .env
set +a

API_PORT="${PGVAULT_API_PORT:-8080}"
WEB_PORT="${PGVAULT_WEB_PORT:-3000}"
BUCKET="${PGVAULT_DEFAULT_BUCKET:-pgvault-backups}"

echo "[pgvault] Starting full stack (app-db, target-db, s3, api, worker, web)..."
docker compose up -d --build

echo "[pgvault] Waiting for API healthcheck on http://127.0.0.1:${API_PORT}/healthz ..."
for i in $(seq 1 60); do
  if curl -sf "http://127.0.0.1:${API_PORT}/healthz" >/dev/null 2>&1; then
    break
  fi
  if [ "$i" -eq 60 ]; then
    echo "Error: API failed to become healthy within 60s. Check 'docker compose logs api'." >&2
    exit 1
  fi
  sleep 1
done

echo "[pgvault] Waiting for Dashboard on http://127.0.0.1:${WEB_PORT} ..."
for i in $(seq 1 60); do
  if curl -sf "http://127.0.0.1:${WEB_PORT}" >/dev/null 2>&1; then
    break
  fi
  if [ "$i" -eq 60 ]; then
    echo "Warning: Web dashboard did not respond within 60s. Check 'docker compose logs web'." >&2
  fi
  sleep 1
done

cat <<EOF

========================================================================
  PGVault is running!
========================================================================
  Dashboard URL  : http://localhost:${WEB_PORT}
  API URL        : http://localhost:${API_PORT}
  API Key        : ${PGVAULT_API_KEY:-<unset>}

  Local Dev S3   : http://s3:4566 (host: http://127.0.0.1:4566)
  Default Bucket : ${BUCKET} (Region: us-east-1, ForcePathStyle: true)
  Demo Target DB : postgres://target_admin:target_dev_password@target-db:5432/customer_app?sslmode=disable

  Tip: Your dashboard is pre-configured to auto-connect using .env.
       Store PGVAULT_KEK_HEX from .env in a secure password manager!
========================================================================
EOF
